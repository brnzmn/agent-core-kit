def _find_core():
    env = os.environ.get('AGENT_CORE_DIR')
    if env:
        return os.path.abspath(os.path.expanduser(env))
    try:
        with open(os.path.join(_HERE, '.core-dir'), encoding='utf-8') as fh:
            got = fh.read().strip()
        if got:
            return os.path.abspath(os.path.expanduser(got))
    except OSError:
        pass
    repo = os.path.dirname(os.path.dirname(_HERE))  # claude/hooks/common.py inside a kit checkout
    if os.path.isfile(os.path.join(repo, 'install.sh')) and os.path.isdir(os.path.join(repo, 'adapters')):
        return repo
    return os.path.join(HOME, 'agent-core-kit')


