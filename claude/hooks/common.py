def tilde(path):
    """path with the home folder written as ~, for messages and commands shown to people."""
    p = os.path.abspath(os.path.expanduser(path))
    return '~' + p[len(HOME):] if p == HOME or p.startswith(HOME + os.sep) else p


def kit_cmd(rel, interpreter=None):
    """A printable command for a kit script, e.g. kit_cmd('bin/trash.py') -> 'python3 ~/agent-core-kit/bin/trash.py'."""
    path = tilde(os.path.join(CORE, rel))
    if any(c in path for c in ' \t\'"$`'):
        path = '"%s"' % os.path.join(CORE, rel).replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('`', '\\`')
    if interpreter is None:
        interpreter = 'python3' if rel.endswith('.py') else ('bash' if rel.endswith('.sh') else '')
    return (interpreter + ' ' + path).strip()


def config(reload=False):
    """DEFAULTS merged with LOCAL/config.json (one level deep for dict values). Never raises."""
    global _CONFIG
    if _CONFIG is not None and not reload:
        return _CONFIG
    out = json.loads(json.dumps(DEFAULTS))
    try:
        with open(CONFIG_PATH, encoding='utf-8') as fh:
            mine = json.load(fh)
    except (OSError, ValueError):
        mine = {}
    for key, value in (mine.items() if isinstance(mine, dict) else []):
        if key.startswith('_'):
            continue
        if isinstance(out.get(key), dict) and isinstance(value, dict):
            out[key] = dict(out[key], **value)
        else:
            out[key] = value
    _CONFIG = out
    return out


def user():
    return (config().get('user_name') or '').strip() or 'the user'


def protected_re():
    """Regex matching a configured protected folder as a whole path component; never matches when none are set."""
    names = []
    for d in config().get('protected_dirs') or []:
        d = str(d).strip().rstrip('/')
        if d:
            names.append(re.escape(os.path.basename(os.path.expanduser(d))))
    if not names:
        return re.compile(r'(?!x)x')
    return re.compile(r'(^|[/=:])(' + '|'.join(sorted(set(names))) + r')(/|$)')


HEADER = ('<!-- Generated by {kit}/bin/build.py from local/AGENTS.md + adapters/{a}.md. Changes belong in '
          'local/AGENTS.md (through /learn) or local/{a}.md, followed by: bash {kit}/install.sh --sync -->\n\n')


def render(text):
    """Fill the kit placeholders in shipped markdown: {{KIT}} is the kit folder (with ~), {{USER}} the user's name."""
    name = user()
    if name == 'the user':  # no name set: "The user" where the placeholder starts a sentence or a line
        text = re.sub(r'(^\s*(?:[-*|#]\s*)*|[.!?:]\s+)\{\{USER\}\}', lambda m: m.group(1) + 'The user', text, flags=re.M)
    return text.replace('{{KIT}}', tilde(CORE)).replace('{{USER}}', name)


