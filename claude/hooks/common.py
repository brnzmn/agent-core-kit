def read(path):
    with open(path, encoding='utf-8', errors='replace') as fh:
        return fh.read()


def count_lines(text):
    return text.count('\n') + (1 if text and not text.endswith('\n') else 0)


def build_text(adapter):
    """The generated global instructions for a tool. Raises OSError when the rulebook is missing (run install.sh)."""
    core = read(RULEBOOK).rstrip('\n') + '\n'
    ad = read(os.path.join(CORE, 'adapters', adapter + '.md'))
    mine = os.path.join(LOCAL, adapter + '.md')
    extra = ('\n' + read(mine).strip('\n') + '\n') if os.path.isfile(mine) else ''
    return render(HEADER.format(a=adapter, kit=tilde(CORE)) + core + ad.rstrip('\n') + '\n' + extra)


def instruction_kind(path, text=None):
    """Return (kind, line budget) for an instruction file, or (None, None)."""
    p = os.path.abspath(path)
    base = os.path.basename(p)
    if p == os.path.abspath(RULEBOOK):
        return 'core', BUDGETS['core']
    if (p.startswith(os.path.join(os.path.abspath(CORE), 'adapters') + os.sep) and p.endswith('.md')) or \
            p in (os.path.join(LOCAL, 'claude.md'), os.path.join(LOCAL, 'codex.md')):
        return 'adapter', BUDGETS['adapter']
    if (os.sep + os.path.join('.claude', 'rules') + os.sep) in p and p.endswith('.md'):
        return 'rule', BUDGETS['rule']
    if base in ('AGENTS.md', 'GEMINI.md'):
        return 'agents', BUDGETS['agents']
    if base in ('CLAUDE.md', 'CLAUDE.local.md'):
        if text is not None and re.search(r'^\s*@\S*AGENTS\.md\s*$', text, re.M):
            return 'claude_adapter', BUDGETS['claude_adapter']
        return 'claude_full', BUDGETS['claude_full']
    return None, None


_LOG_ALWAYS = (r"(build status|project status|current status|status updates?|progress log|changelog|change log|"
               r"session log|session notes|work log|build log|dev log|done so far|recent changes|recent work|"
               r"what'?s done|what'?s new|latest updates?)")
_LOG_BARE = r"(status|progress|done|completed|in progress)"
LOG_HEADING = re.compile(r"^\s{0,3}#{1,6}\s*(" + _LOG_ALWAYS + r"\b.*|" + _LOG_BARE +
                         r"\s*(\(.*\)|\d{4}-\d\d(-\d\d)?.*)?)\s*$", re.I)
DATED_ENTRY = re.compile(r"^\s*([-*+]\s+|\d+[.)]\s+)?(\*\*|__)?[\[(]?20\d\d-\d\d-\d\d\b.*\b(added|fixed|shipped|merged|"
                         r"landed|implemented|completed|done|wired|migrated|deployed|released|refactored|rewrote|removed|"
                         r"now (sets|uses|has|runs|supports))\b", re.I)
STATUS_MARK = re.compile(r"(✅|☑|✔|\bDONE\b|\bWIP\b|\bNOT (YET )?(MERGED|DONE|PROVISIONED|SHIPPED)\b|\bIN PROGRESS\b)")


def log_signals(lines):
    """Split lines into (log headings, dated progress entries, status marks), ignoring code fences."""
    heads, dated, marks = [], [], []
    in_code = False
    for line in lines:
        if line.strip().startswith('```'):
            in_code = not in_code
            continue
        if in_code:
            continue
        if LOG_HEADING.match(line):
            heads.append(line)
        elif DATED_ENTRY.search(line):
            dated.append(line)
        elif STATUS_MARK.search(line):
            marks.append(line)
    return heads, dated, marks


def log_entry(lines):
    """The first log-shaped line among added lines (a log heading, 2+ dated entries, or 3+ dated/status lines)."""
    heads, dated, marks = log_signals(lines)
    if heads or len(dated) >= 2 or len(dated) + len(marks) >= 3:
        return (heads + dated + marks)[0].strip()[:120]
    return None


def added_lines(old, new):
    pool = Counter(old.splitlines())
    out = []
    for line in new.splitlines():
        if pool.get(line, 0) > 0:
            pool[line] -= 1
        else:
            out.append(line)
    return out


START_CORRECTION = re.compile(
    r"^\W*(no(?!\s+(problem|worries|need|rush|thanks|idea|doubt))\b|nope\b|wrong\b|stop (it|that|doing)\b|"
    r"not (that|this|what)\b|that'?s not\b|thats not\b|i said\b|i told you\b|i asked\b|why (did|are|would) you\b|"
    r"revert\b|undo\b|hay\u0131r\b|yanl\u0131\u015f\b|dur\b|no hagas\b)", re.I)
ANY_CORRECTION = re.compile(
    r"\b(wrong|incorrect|not what i (asked|wanted|said)|that'?s not (it|right|what)|you (forgot|missed|ignored|broke|"
    r"deleted|skipped)|i (already )?(said|told you|asked)|again\?|still (broken|wrong|failing)|didn'?t (i|you)|"
    r"why did you|stop doing|you keep)\b", re.I)
FRUSTRATION = re.compile(r"\b(fuck\w*|shit\w*|wtf|ffs|bullshit|damn it|goddamn)\b", re.I)
STRONG_STANDING = re.compile(r"\b(from now on|going forward|remember (this|that)|don'?t ever|never again|for future reference|note for next time)\b", re.I)
STANDING = re.compile(r"\b(always|never|every time)\b", re.I)


def score_prompt(text):
    """Heuristic score for 'this prompt corrects the agent'. 2 or more gets logged."""
    t = (text or '').strip()
    if not t or t.startswith('/') or t.startswith('<'):
        return 0, []
    score, sig = 0, []
    if START_CORRECTION.search(t[:80]):
        score += 2
        sig.append('starts-with-correction')
    hits = set(m.group(0).lower() for m in ANY_CORRECTION.finditer(t))
    if hits:
        score += min(len(hits), 2)
        sig.append('correction x%d' % len(hits))
    if FRUSTRATION.search(t):
        score += 2
        sig.append('frustration')
    if STRONG_STANDING.search(t):
        score += 2
        sig.append('standing-instruction')
    elif STANDING.search(t):
        score += 1
        sig.append('always-never')
    if len(re.findall(r'\b[A-Z]{4,}\b', t)) >= 3 or '!!' in t:
        score += 1
        sig.append('emphasis')
    return score, sig


def make_id(rec):
    key = '%s|%s' % (rec.get('session', ''), (rec.get('text') or '')[:300])
    return hashlib.sha1(key.encode('utf-8', 'ignore')).hexdigest()[:12]


def append_inbox(rec):
    os.makedirs(INBOX, exist_ok=True)
    rec.setdefault('ts', time.strftime('%Y-%m-%dT%H:%M:%S'))
    rec.setdefault('id', make_id(rec))
    with open(os.path.join(INBOX, time.strftime('%Y-%m') + '.jsonl'), 'a', encoding='utf-8') as fh:
        fh.write(json.dumps(rec, ensure_ascii=False) + '\n')
    return rec['id']


def inbox_records():
    out = []
    if not os.path.isdir(INBOX):
        return out
    for fn in sorted(os.listdir(INBOX)):
        if not fn.endswith('.jsonl'):
            continue
        try:
            with open(os.path.join(INBOX, fn), encoding='utf-8', errors='replace') as fh:
                for line in fh:
                    line = line.strip()
                    if line:
                        try:
                            out.append(json.loads(line))
                        except ValueError:
                            pass
        except OSError:
            pass
    return out


def load_state():
    try:
        with open(STATE_FILE, encoding='utf-8') as fh:
            return json.load(fh)
    except Exception:
        return {}


def save_state(state):
    os.makedirs(LEARN, exist_ok=True)
    tmp = STATE_FILE + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as fh:
        json.dump(state, fh, indent=1)
    os.replace(tmp, STATE_FILE)


def learning_backlog():
    """(number of unreviewed inbox records, timestamp of the last review or None)."""
    st = load_state()
    done = set(st.get('processed_ids') or [])
    ids = set(r.get('id') for r in inbox_records() if r.get('id') and r.get('id') not in done)
    return len(ids), st.get('last_review_ts')


def repo_root(start):
    if not start:
        return None
    p = os.path.abspath(os.path.expanduser(start))
    while True:
        if os.path.exists(os.path.join(p, '.git')):
            return p
        parent = os.path.dirname(p)
        if parent == p:
            return None
        p = parent


def in_icloud(path):
    if sys.platform != 'darwin' or not config().get('icloud_warning', True):
        return False
    p = os.path.abspath(path)
    return any(p == r or p.startswith(r + os.sep) for r in ICLOUD_ROOTS)


# Codex user turns the user did not type: automation heartbeats, delegations from another agent, question replies
CODEX_NOT_TYPED = re.compile(r'^\s*<(heartbeat|codex_delegation|send_user_message_question_reply)\b')
CODEX_BROWSER = re.compile(r'(?s)^\s*<in-app-browser-context\b.*?</in-app-browser-context>\s*')
CODEX_REQUEST = '## My request for Codex:'
CODEX_AGENT_CLIENTS = ('Claude Code',)  # app-server clients that send another agent's prompts (codex-plugin-cc)


def codex_meta(path):
    """session_meta of a rollout (its first line), or None when it cannot be read."""
    try:
        if path.endswith('.zst'):
            with subprocess.Popen(['zstd', '-dcq', path], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL) as proc:
                first = proc.stdout.readline()
                proc.kill()
        else:
            with open(path, 'rb') as fh:
                first = fh.readline()
        ev = json.loads(first)
    except (OSError, ValueError):
        return None
    return ev.get('payload') if ev.get('type') == 'session_meta' else None


def codex_typed(meta):
    """Only sessions the user drove: not subagent or guardian threads (their user turns come from the parent agent),
    not codex exec or MCP runs (scripted prompts), not the Claude plugin's app-server threads."""
    src = meta.get('source')
    return not (meta.get('parent_thread_id') or isinstance(src, dict) or src in ('exec', 'mcp')
                or meta.get('thread_source') not in (None, 'user') or meta.get('originator') in CODEX_AGENT_CLIENTS)


def codex_user_text(text):
    if CODEX_NOT_TYPED.match(text):
        return ''
    text = CODEX_BROWSER.sub('', text)
    if CODEX_REQUEST in text:
        text = text.split(CODEX_REQUEST, 1)[1]
    return text.strip()
