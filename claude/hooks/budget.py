#!/usr/bin/env python3
"""agent-core PreToolUse check for instruction files (Edit, Write, MultiEdit).

Blocks an edit that puts an instruction file over its line budget (unless the
edit shrinks the file) or adds build-log or status entries, and blocks direct
edits to the generated global files. Prints nothing to allow.
Its own errors never block an edit.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402


def new_text_for(tool, tool_input, old):
    if tool == 'Write':
        return tool_input.get('content') or ''
    if tool == 'Edit':
        o, n = tool_input.get('old_string') or '', tool_input.get('new_string') or ''
        if not o:
            return n if not old else None
        if o not in old:
            return None
        return old.replace(o, n) if tool_input.get('replace_all') else old.replace(o, n, 1)
    if tool == 'MultiEdit':
        text = old
        for e in tool_input.get('edits') or []:
            o, n = e.get('old_string') or '', e.get('new_string') or ''
            if not o or o not in text:
                return None
            text = text.replace(o, n) if e.get('replace_all') else text.replace(o, n, 1)
        return text
    return None


def decide(decision, reason):
    print(json.dumps({'hookSpecificOutput': {'hookEventName': 'PreToolUse', 'permissionDecision': decision,
                                             'permissionDecisionReason': 'agent-core: ' + reason}}))


def deny(reason):
    decide('deny', reason)


def main():
    try:
        data = json.load(sys.stdin)
    except Exception:
        return
    try:
        tool = data.get('tool_name') or ''
        tool_input = data.get('tool_input') or {}
        path = tool_input.get('file_path') or ''
        if not path:
            return
        path = os.path.abspath(os.path.expanduser(path))
        if path in common.GENERATED:
            deny('This file is generated by the kit. Propose the change with /learn, or edit local/AGENTS.md (%s) '
                 'or local/claude.md / local/codex.md, then run: %s --sync'
                 % (common.tilde(common.RULEBOOK), common.kit_cmd('install.sh')))
            return
        if common.instruction_kind(path)[0] is None:
            return
        try:
            old = common.read(path)
        except FileNotFoundError:
            old = ''
        new = new_text_for(tool, tool_input, old)
        if new is None:
            return
        kind, budget = common.instruction_kind(path, new)
        example = common.log_entry(common.added_lines(old, new))
        if example:
            deny('This adds a build log or status entry to an instruction file ("%s"). Those load every session and '
                 'rot. Put it in docs/build-log.md, the PR, or the issue tracker.' % example)
            return
        old_n, new_n = common.count_lines(old), common.count_lines(new)
        if budget and new_n > budget and new_n > old_n:
            name = os.path.basename(path)
            if old_n > budget:
                deny('%s is already %d lines (budget %d) and this adds more. Put it in docs/ or .claude/rules/, '
                     'or run /instructions to slim the file first.' % (name, old_n, budget))
            else:
                deny('This would make %s %d lines; its budget is %d. Move logs and status to docs/, procedures to a '
                     'skill, and path-specific rules to .claude/rules/.' % (name, new_n, budget))
    except Exception as exc:
        common.log_error('budget', exc)


if __name__ == '__main__':
    main()
