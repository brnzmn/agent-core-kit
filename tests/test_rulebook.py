"""The rulebook and the files built from it never trip the kit's own Stop hook checks.

An agent that quotes or follows the rules must not be blocked for a step list or an offer,
and a checklist written the way the rulebook asks (ending on a Blocked: line) must pass.
"""
import contextlib
import io
import os
import re
import shutil
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from helpers import BIN, CORE, HOOKS, make_local  # noqa: E402

sys.path.insert(0, HOOKS)
sys.path.insert(0, BIN)
import common  # noqa: E402
import lint  # noqa: E402
import stop_steps  # noqa: E402

SHOUT = re.compile(r'\b(MUST|NEVER|ALWAYS|IMPORTANT|CRITICAL|MANDATORY|REQUIRED)\b')
TEMPLATE = os.path.join(CORE, 'templates', 'core', 'AGENTS.md')


def rulebook_texts():
    """The shipped default rulebook, and the global files built from it (a copy of it stands in for local/AGENTS.md)."""
    local = make_local({'user_name': 'Alex'})
    try:
        with mock.patch.multiple(common, LOCAL=local, RULEBOOK=os.path.join(local, 'AGENTS.md'),
                                 CONFIG_PATH=os.path.join(local, 'config.json'), CORE=CORE):
            common.config(reload=True)
            try:
                return {'templates/core/AGENTS.md': common.read(TEMPLATE),
                        'built CLAUDE.md': common.build_text('claude'), 'built Codex AGENTS.md': common.build_text('codex')}
            finally:
                common.config(reload=True)
    finally:
        shutil.rmtree(local, ignore_errors=True)


class Rulebook(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.texts = rulebook_texts()

    def test_no_sentence_reads_as_a_step_for_the_user(self):
        for name, text in self.texts.items():
            steps = [u for u in stop_steps.SENTENCE.split(stop_steps.visible(text)) if stop_steps.is_step(u)]
            self.assertEqual(steps, [], name)

    def test_no_paragraph_ends_on_an_offer(self):
        for name, text in self.texts.items():
            for para in re.split(r'\n\s*\n', text):
                self.assertIsNone(stop_steps.decide(para, []), '%s: %s' % (name, para[:120]))

    def test_check_is_not_vacuous(self):
        for name, text in self.texts.items():
            self.assertIsNone(stop_steps.BLOCKER.search(stop_steps.visible(text)), name)

    def test_shape(self):
        core = self.texts['templates/core/AGENTS.md']
        self.assertLessEqual(common.count_lines(core), common.BUDGETS['core'])
        self.assertEqual(SHOUT.findall(core), [])
        continuation = [l for l in core.splitlines() if l.startswith('  ')]
        self.assertEqual(continuation, [], 'one line per rule')

    def test_built_files_are_filled_in_and_carry_the_header(self):
        for name in ('built CLAUDE.md', 'built Codex AGENTS.md'):
            text = self.texts[name]
            self.assertTrue(text.startswith('<!-- Generated by'), name)
            self.assertNotIn('{{', text, name)
            self.assertIn('Alex', text, name)

    def test_checklist_in_the_rulebook_format_passes(self):
        reply = ('Deployed everything except the DNS record.\n\n1. Open Cloudflare DNS for example.com\n'
                 '2. Add the CNAME below\n```\napp CNAME cname.vercel-dns.com\n```\n3. Save\n'
                 'Blocked: the Cloudflare token has no DNS edit scope; CLOUDFLARE_API_TOKEN needs Zone.DNS edit.')
        self.assertIsNone(stop_steps.decide(reply, []))


class Lint(unittest.TestCase):
    """bin/lint.py on the shipped template and on a repo."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def run_lint(self, *paths):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = lint.main(['lint.py'] + list(paths))
        return code, buf.getvalue()

    def write(self, rel, text):
        path = os.path.join(self.tmp, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w') as fh:
            fh.write(text)

    def test_the_shipped_template_is_within_budget(self):
        code, out = self.run_lint(TEMPLATE)
        self.assertEqual(code, 0, out)
        self.assertIn('/120 lines', out)

    def test_over_budget_and_log_sections_fail(self):
        self.write('AGENTS.md', ''.join('- Rule %d.\n' % i for i in range(160)))
        self.write('CLAUDE.md', '@AGENTS.md\n')
        code, out = self.run_lint(self.tmp)
        self.assertEqual(code, 1)
        self.assertIn('160 lines, budget 150', out)
        self.write('AGENTS.md', '# Rules\n\n## Status\n- 2026-10-19 shipped the login page\n')
        code, out = self.run_lint(self.tmp)
        self.assertEqual(code, 1)
        self.assertIn('log or status section', out)

    def test_clean_repo_passes_and_a_missing_claude_md_is_a_warning(self):
        self.write('AGENTS.md', '# Rules\n\n- Run the tests before a PR.\n')
        code, out = self.run_lint(self.tmp)
        self.assertEqual(code, 0, out)
        self.assertIn('AGENTS.md without CLAUDE.md', out)

    def test_icloud_note_names_no_fixed_path(self):
        self.write('AGENTS.md', '# Rules\n\n- Be brief.\n')
        self.write('CLAUDE.md', '@AGENTS.md\n')
        with mock.patch.object(common, 'in_icloud', return_value=True):
            code, out = self.run_lint(self.tmp)
        self.assertIn('iCloud', out)
        self.assertNotIn('Projects', out)

    def test_icloud_check_only_fires_on_macos(self):
        self.write('AGENTS.md', '# Rules\n\n- Be brief.\n')
        self.write('CLAUDE.md', '@AGENTS.md\n')
        with mock.patch.object(common.sys, 'platform', 'linux'), \
                mock.patch.object(common, 'ICLOUD_ROOTS', (self.tmp,)):
            code, out = self.run_lint(self.tmp)
        self.assertNotIn('iCloud', out)

    def test_no_argument_run_lints_the_kit_sources(self):
        local = make_local({})
        self.addCleanup(shutil.rmtree, local, True)
        with mock.patch.multiple(common, LOCAL=local, RULEBOOK=os.path.join(local, 'AGENTS.md')):
            code, out = self.run_lint()
        self.assertEqual(code, 0, out)
        self.assertIn('adapters/claude.md', out)
        self.assertIn('templates/core/AGENTS.md', out)


if __name__ == '__main__':
    unittest.main()
